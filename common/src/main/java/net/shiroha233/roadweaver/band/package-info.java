/* 文件职责：把拓扑层给出的准测地线平滑成曲率受限的曲线（纯线性求解）。 */
/**
 * 几何层：弹性带（Elastic Band）。
 *
 * <h2>只做一件事：曲率最小化</h2>
 * <p>度量层已经处理了长度、坡度、障碍；拓扑层已经决定了走位。
 * 这一层唯一剩下的职责是<b>把折线变得曲率受限且光滑</b>。</p>
 *
 * <pre>
 * min  ∫ |γ''|² ds  +  μ ∫ |γ − γ₀|² ds
 * s.t. γ(0) = 起点,  γ(1) = 终点
 * </pre>
 *
 * <h2>为什么是线性的（这一点很关键）</h2>
 * <p>只含二阶差分与保形项时，离散化后对每个点求偏导得到一个<b>五对角</b>方程：</p>
 * <pre>
 * 2[ γ_{j-2} − 4γ_{j-1} + 6γ_j − 4γ_{j+1} + γ_{j+2} ] + 2μ(γ_j − γ₀_j) = 0
 * </pre>
 * <p>即 thin-plate 样条的刚度矩阵，对称正定、带宽 5 —— <b>一次 PCG 求解即可</b>。</p>
 *
 * <p><b>反面教材（必须避免）</b>：如果把坡度项也塞进这个泛函，分母里的
 * {@code |Δγ|} 会让问题变成非线性，只能靠 Gauss-Newton 迭代；
 * 那是 2026-11-12 讨论的第一版方案，已被这一版取代。</p>
 *
 * <h2>这一层替代掉了什么</h2>
 * <p>旧实现里这 8 段全是为了修几何 artifact，现在一并删除：
 * DP 简化、Catmull-Rom 样条、1-2-1 平滑、relax 拉回、锯齿检测、
 * 急弯冻结、窗口 splice、{@code fine regenerate}。</p>
 *
 * <p>本包只允许依赖 {@code topology} 与 {@code foundation}。
 * <b>禁止</b>依赖 {@code pipeline}。</p>
 *
 * @see net.shiroha233.roadweaver.topology
 */
