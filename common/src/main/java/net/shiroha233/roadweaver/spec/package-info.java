/* 文件职责：spec 包 —— 一条路的「唯一权威表示」与结构不变量校验。 */
package net.shiroha233.roadweaver.spec;

/*
 * ============================================================================
 * spec 包现在只有一个类：RoadSpec
 * ============================================================================
 *
 * 【它做什么】
 *   把一条路的三种事实（站序列 / 剖面 / 区间）对齐成一个不可变对象，
 *   并在构造期校验结构不变量：
 *     · profile 长度必须等于站数（否则后面每次「按站取高度」都在越界或错位）
 *     · 区间不许越界、不许起止颠倒、不许重叠、必须按起点有序
 *     · 区间端点必须能在站序列里唯一定位（精确匹配 → 同 XZ 且全序列唯一 → 否则失败）
 *
 * 【为什么区间端点的定位值得单独校验】
 *   0.9.036 修过一个真缺陷：BridgeShareService.collectBridges 用 BlockPos.equals
 *   去站序列里反查区间端点，而路网合并会重建站序列（Y 漂一格）⇒ 整座桥被静默丢掉，
 *   表现为 bridgeShareCandidates=0。修法是「同 XZ 唯一才认、有歧义就放弃」。
 *   RoadSpec 把那套判定固化成了不变量 —— 对不上就抛异常，不静默跳过。
 *
 * 【它现在的消费者】
 *   Road.logSpecIntegrity(...) —— 每条路完成时（RoadQualityMetrics.record 之后）
 *   跑一次自检，打一行 INFO 摘要；违规只 warn 且限流，绝不影响生成。
 *   这条自检的价值是：区间端点若在站序列里对不上，规划阶段就报出来，
 *   而不是等施工时发现桥没了再回头查。
 *
 * 【2026-11-13 删掉了什么，以及为什么】
 *   删了 BuildPlan（109 行）与 BuildPlanCompiler（135 行）。
 *   它们想把「每一列该做什么」物化成纯数据，动机是好的（让判定可单测），
 *   但那个目标**已经由 SegmentPaver.classifyProtectedColumn 达成** ——
 *   它是静态纯函数，有 ProtectedColumnActionTest 盯着。
 *   而接线的真实代价是：要先单独遍历一遍所有列去填 protectionRank 矩阵
 *   （每列 2 次 RoadConstructionSafety 世界查询），才能编译出 Plan，
 *   等于把施工热路径上的世界查询翻倍。收益小于成本，所以删。
 *
 *   BuildPlan 自己的注释也写着「接线放在 S7 第 2 级」「先定形状，后填内容」——
 *   现在填内容的时机到了，判断结果是不该填。留着它只会变成又一份
 *   「写得挺好但没人用」的孤岛。
 */