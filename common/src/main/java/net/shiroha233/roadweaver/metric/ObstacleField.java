/* 文件职责：度量层对「障碍」的唯一依赖 —— 归一化势值；不含避让判据。 */
package net.shiroha233.roadweaver.metric;

/**
 * 障碍势场（度量层的输入端口）。
 *
 * <h2>势而不是布尔</h2>
 * <p>旧实现的避让判据是布尔式的「这个点能不能走」。布尔判据在<b>边界上没有梯度</b> ——
 * 搜索算法不知道哪边「更远离障碍」，只能贴着边界走或直接撞墙，
 * 这也是旧实现里「端点禁区」需要单独挖洞、`PROTECTED_GAP` 缺 fail-safe 的土壤。</p>
 *
 * <p>这里改成<b>连续势</b>：0 表示完全可走，越大越接近障碍。路径自然会往势低处走，
 * 不需要额外的「禁区」逻辑。势的值由距离变换生成（{@code O(n)}，精确）。</p>
 *
 * <h2>与判据的关系</h2>
 * <p><b>本接口不改任何避让判据。</b>「哪些方块算障碍」「村庄包围盒怎么算」
 * 仍然由 {@code foundation.constraint} 里的现有判据决定（用户已拍板：
 * 村庄裁切包围盒保留原判据）。本接口只是把那个判据的<b>结果</b>换成可微的场。</p>
 *
 * @see FinslerMetric
 */
public interface ObstacleField {

    /**
     * 该点的障碍势，约定 {@code 0 = 完全可走}，越大越不可走。
     *
     * <p>实现方负责归一化；度量层不假设上界，只用它的相对大小。</p>
     */
    double potential(int x, int z);

    /**
     * 该点是否<b>绝对不可通行</b>（硬约束）。
     *
     * <h2>为什么软势之外还需要硬不可通行</h2>
     * <p>软势只会让路径「尽量少穿」，永远不会真正隔离一块区域 ——
     * 因为求解器总能付代价硬穿过去。但现实里有真正过不去的格子：
     * 别人的结构主体、无法施工的立柱、世界边界之外。</p>
     *
     * <p>没有这个概念，拓扑层就无法判断「这个端点根本连不上」，
     * 只能给出一个天文数字的距离然后假装连通 —— 那正是旧实现
     * 「{@code PROTECTED_GAP} 缺 fail-safe」的同类问题。</p>
     *
     * <p>默认返回 {@code false}（处处可通行），只有明确需要硬约束时才覆写。
     * 注意：<b>这不是避让判据</b>。「哪些方块算障碍」仍由 foundation 的现有判据决定
     * （村庄裁切包围盒保留原判据）；本方法只是把其中<b>真正不可施工</b>的那部分
     * 标出来。</p>
     */
    default boolean impassable(int x, int z) {
        return false;
    }

    /** 处处无障碍的常量场（默认实现，测试与「不启用避让」时用）。 */
    ObstacleField NONE = (x, z) -> 0.0;
}
